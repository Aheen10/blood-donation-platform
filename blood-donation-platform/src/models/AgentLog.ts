import mongoose, { Schema, InferSchemaType, Model } from "mongoose";

// Every AI/agent decision is logged so admins can see why a donor was notified.
const AgentLogSchema = new Schema(
  {
    request: { type: Schema.Types.ObjectId, ref: "BloodRequest", required: true },
    action: {
      type: String,
      enum: ["match", "notify", "escalate", "skip", "fulfill", "remind", "close"],
      required: true,
    },
    round: { type: Number, default: 0 },
    donor: { type: Schema.Types.ObjectId, ref: "User", default: null },
    reason: { type: String, required: true },
    // Optional human-readable summary generated by Gemini
    summary: { type: String },
    meta: { type: Schema.Types.Mixed },
  },
  { timestamps: true }
);

AgentLogSchema.index({ request: 1, createdAt: -1 });

export type AgentLogDoc = InferSchemaType<typeof AgentLogSchema>;
const AgentLog: Model<AgentLogDoc> =
  mongoose.models.AgentLog || mongoose.model<AgentLogDoc>("AgentLog", AgentLogSchema);
export default AgentLog;